/* =========================================================
   1. NORMALISASI KE SKALA 0–100
   ========================================================= */
function normalisasi($nilai, $min, $max)
{
    if ($max == $min) {
        return 0;
    }

    $hasil = (($nilai - $min) / ($max - $min)) * 100;

    if ($hasil < 0) {
        $hasil = 0;
    }

    if ($hasil > 100) {
        $hasil = 100;
    }

    return $hasil;
}


/* =========================================================
   2. MEMBERSHIP FUNCTION INPUT
   =========================================================
   Low    : 0–50
   Medium : 25–75
   High   : 50–100
   ========================================================= */
function fuzzify($x)
{
    /* LOW */
    if ($x <= 25) {
        $low = 1;
    } elseif ($x < 50) {
        $low = (50 - $x) / 25;
    } else {
        $low = 0;
    }

    /* MEDIUM */
    if ($x <= 25 || $x >= 75) {
        $medium = 0;
    } elseif ($x < 50) {
        $medium = ($x - 25) / 25;
    } else {
        $medium = (75 - $x) / 25;
    }

    /* HIGH */
    if ($x <= 50) {
        $high = 0;
    } elseif ($x < 75) {
        $high = ($x - 50) / 25;
    } else {
        $high = 1;
    }

    return [
        'low'    => $low,
        'medium' => $medium,
        'high'   => $high
    ];
}


/* =========================================================
   3. MEMBERSHIP FUNCTION OUTPUT STRESS
   ========================================================= */

function muStressLow($z)
{
    if ($z <= 25) {
        return 1;
    } elseif ($z < 50) {
        return (50 - $z) / 25;
    }

    return 0;
}


function muStressMedium($z)
{
    if ($z <= 25 || $z >= 75) {
        return 0;
    } elseif ($z < 50) {
        return ($z - 25) / 25;
    }

    return (75 - $z) / 25;
}


function muStressHigh($z)
{
    if ($z <= 50) {
        return 0;
    } elseif ($z < 75) {
        return ($z - 50) / 25;
    }

    return 1;
}


/* =========================================================
   4. DEFUZZIFIKASI CENTROID MAMDANI
   ========================================================= */

function defuzzifyMamdani(
    $alpha_rendah,
    $alpha_sedang,
    $alpha_tinggi
) {
    $numerator = 0;
    $denominator = 0;

    for ($z = 0; $z <= 100; $z++) {

        /* Implikasi MIN */
        $muLow = min(
            $alpha_rendah,
            muStressLow($z)
        );

        $muMedium = min(
            $alpha_sedang,
            muStressMedium($z)
        );

        $muHigh = min(
            $alpha_tinggi,
            muStressHigh($z)
        );

        /* Agregasi MAX */
        $mu = max(
            $muLow,
            $muMedium,
            $muHigh
        );

        $numerator += $z * $mu;
        $denominator += $mu;
    }

    if ($denominator == 0) {
        return 0;
    }

    return $numerator / $denominator;
}


/* =========================================================
   5. KATEGORI STRES
   ========================================================= */

function kategoriStress($score)
{
    // Hitung derajat keanggotaan output
    $low = muStressLow($score);
    $medium = muStressMedium($score);
    $high = muStressHigh($score);

    // Tentukan kategori berdasarkan derajat keanggotaan terbesar
    $maxMembership = max($low, $medium, $high);

    if ($maxMembership == $low) {
        return 'Rendah';
    } elseif ($maxMembership == $medium) {
        return 'Sedang';
    } else {
        return 'Tinggi';
    }
}


